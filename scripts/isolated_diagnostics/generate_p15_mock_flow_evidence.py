"""Export reproducible synthetic Mock-only controller evidence, with no credentials."""

import asyncio
import json
from pathlib import Path
import tempfile

import httpx

from scripts.isolated_diagnostics import p15_controlled_mock_v1 as controlled
from scripts.isolated_diagnostics.p15_head_insertion_engine import canonical
from scripts.tests.test_p15_controlled_mock_v1 import attest, package_grant, handler_for

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "docs/acceptance/phase-1.5-visible-migration-t102"


def main() -> None:
    OUTPUT.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as temporary:
        path = Path(temporary) / "package.db"
        seen: list[object] = []
        executor = controlled.Controller(
            path,
            package_grant(path),
            httpx.MockTransport(handler_for("B", seen)),
            selected=("slot", "B"),
        )
        records = {}
        try:
            for arm in ("B", "C"):
                if arm == "C":
                    executor.select_slot("slot", "C")
                    executor.transport = httpx.MockTransport(handler_for("C", seen))
                result = asyncio.run(executor.run(attest))
                attempts = []
                for row in executor.db.execute(
                    "SELECT * FROM attempts WHERE slot=? AND arm=? ORDER BY ordinal",
                    ("slot", arm),
                ):
                    record = dict(row)
                    record["request"] = bytes(record["request"]).decode("utf-8")
                    record["response"] = bytes(record["response"]).decode("utf-8")
                    attempts.append(record)
                records[arm] = {
                    "version": controlled.VERSION,
                    "scope": "synthetic offline fixture; B test output generated by fixture engine, not a model or independent baseline",
                    "real_provider_calls": 0,
                    "independent_semantic_evaluation": False,
                    "grant": executor.grant,
                    "package": executor.package,
                    "result": result,
                    "attempts": attempts,
                }
            for arm, evidence in records.items():
                evidence["batch_status"] = executor.batch_status()
                evidence["batch_attempts"] = executor.db.execute(
                    "SELECT COUNT(*) FROM attempts"
                ).fetchone()[0]
                evidence["ledger_state"] = controlled.ledger_state(executor.db)
                evidence["anchor_lines"] = (
                    Path(str(path) + ".anchor").read_text().splitlines()
                )
                row = executor.db.execute(
                    "SELECT value FROM attestation WHERE slot=? AND arm=?",
                    ("slot", arm),
                ).fetchone()
                evidence["feedback_attestation"] = (
                    json.loads(bytes(row[0])) if row else None
                )
                (OUTPUT / f"{arm.lower()}-mock-flow.json").write_bytes(
                    canonical(evidence) + b"\n"
                )
                print(
                    f"{arm}: {len(evidence['attempts'])} mock HTTP attempts, {len(evidence['result']['versions'])} candidate versions"
                )
        finally:
            executor.close()


if __name__ == "__main__":
    main()
